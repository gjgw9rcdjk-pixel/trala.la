export const fmt = (s, vars = {}) => s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));

// "{n} cards" with the right plural form (1 card / 2 karty / 5 kart).
export function cards(s, n) {
  if (n === 1 && s.cardsOne) return s.cardsOne;
  const few = n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 12 || n % 100 > 14);
  if (few && s.cardsFew) return fmt(s.cardsFew, { n });
  return fmt(s.cardsCount, { n });
}

